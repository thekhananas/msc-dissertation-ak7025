"""Score recorded answers to the private v1 evidence probes."""

from __future__ import annotations

import ast
import json
from pathlib import Path
from typing import Any, Literal, cast

import yaml
from pydantic import Field

from socratic_tutor.benchmark.artifacts import write_immutable_json
from socratic_tutor.benchmark.common import Sha256
from socratic_tutor.benchmark.evaluator.loader import load_and_verify_manifest
from socratic_tutor.benchmark.hashing import model_content_hash
from socratic_tutor.contracts import ContractModel


class EvidenceResponse(ContractModel):
    """One response recorded without evaluator-only expected answers."""

    case_id: str = Field(min_length=1)
    response: str


class EvidenceCaseScore(ContractModel):
    case_id: str
    target_concept: str
    task_family: str
    status: Literal["correct", "incorrect", "invalid"]
    response: str


class EvidenceGroupScore(ContractModel):
    """Accuracy for one concept or task-family subgroup."""

    group: str
    case_count: int = Field(ge=1)
    correct_count: int = Field(ge=0)
    accuracy: float = Field(ge=0.0, le=1.0)


class EvidenceScoreSummary(ContractModel):
    """Private evaluation summary for one complete evidence-response file."""

    schema_version: Literal[1] = 1
    schema_id: Literal["benchmark.evidence_score_summary.v1"] = (
        "benchmark.evidence_score_summary.v1"
    )
    method: Literal["authored_output_parse_v1"] = "authored_output_parse_v1"
    case_count: int = Field(ge=1)
    response_count: int = Field(ge=0)
    correct_count: int = Field(ge=0)
    incorrect_count: int = Field(ge=0)
    invalid_count: int = Field(ge=0)
    accuracy: float = Field(ge=0.0, le=1.0)
    case_scores: tuple[EvidenceCaseScore, ...]
    concept_scores: tuple[EvidenceGroupScore, ...]
    task_family_scores: tuple[EvidenceGroupScore, ...]
    manifest_hash: Sha256
    response_file_hash: Sha256
    summary_hash: Sha256

    @property
    def complete(self) -> bool:
        return self.response_count == self.case_count

    def validate_counts(self) -> EvidenceScoreSummary:
        if self.correct_count + self.incorrect_count + self.invalid_count != self.case_count:
            raise ValueError("Evidence score counts must cover every benchmark case")
        if self.accuracy != self.correct_count / self.case_count:
            raise ValueError("Evidence accuracy does not match correct count")
        if self.summary_hash != model_content_hash(self, exclude={"summary_hash"}):
            raise ValueError("Evidence score summary hash does not match its content")
        return self


class EvidenceScoringError(ValueError):
    """The response file cannot be scored as a complete paired evaluation."""


def score_evidence_responses(
    *,
    manifest_path: Path,
    responses_path: Path,
    output_path: Path,
) -> EvidenceScoreSummary:
    """Score exactly one response for every authored v1 case.

    Expected answers are loaded only from the private evaluator-side test files. The
    response file contains case IDs and proposed replacements only, so it can be
    generated by a model without giving that model access to the answer key.
    """

    manifest = load_and_verify_manifest(manifest_path)
    benchmark_root = manifest_path.resolve().parent
    expected_cases = {item.public.case_id: item for item in manifest.cases}
    responses = _load_responses(responses_path)
    unknown = set(responses) - set(expected_cases)
    missing = set(expected_cases) - set(responses)
    if unknown:
        raise EvidenceScoringError(f"Response file contains unknown cases: {sorted(unknown)}")
    if missing:
        raise EvidenceScoringError(f"Response file is missing cases: {sorted(missing)}")

    scores: list[EvidenceCaseScore] = []
    for case_id, item in expected_cases.items():
        response = responses[case_id]
        expected = _load_expected(
            benchmark_root / item.public.evidence_test_ref,
            case_id=case_id,
        )
        status = _score_one(response, expected)
        scores.append(
            EvidenceCaseScore(
                case_id=case_id,
                target_concept=item.public.target_concept,
                task_family=item.public.task_family,
                status=status,
                response=response,
            )
        )

    correct = sum(score.status == "correct" for score in scores)
    incorrect = sum(score.status == "incorrect" for score in scores)
    invalid = sum(score.status == "invalid" for score in scores)
    content = {
        "schema_version": 1,
        "schema_id": "benchmark.evidence_score_summary.v1",
        "method": "authored_output_parse_v1",
        "case_count": len(scores),
        "response_count": len(responses),
        "correct_count": correct,
        "incorrect_count": incorrect,
        "invalid_count": invalid,
        "accuracy": correct / len(scores),
        "case_scores": tuple(scores),
        "concept_scores": _group_scores(scores, attribute="target_concept"),
        "task_family_scores": _group_scores(scores, attribute="task_family"),
        "manifest_hash": model_content_hash(manifest),
        "response_file_hash": _file_hash(responses_path),
    }
    draft = EvidenceScoreSummary.model_construct(
        _fields_set=set(content),
        **content,
        summary_hash="0" * 64,
    )
    summary = EvidenceScoreSummary.model_validate(
        {**content, "summary_hash": model_content_hash(draft, exclude={"summary_hash"})}
    ).validate_counts()
    write_immutable_json(output_path, summary)
    return summary


def _load_responses(path: Path) -> dict[str, str]:
    responses: dict[str, str] = {}
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as error:
        raise EvidenceScoringError(f"Could not read response file: {path}") from error
    for line_number, line in enumerate(lines, start=1):
        if not line.strip():
            continue
        try:
            response = EvidenceResponse.model_validate(json.loads(line))
        except (json.JSONDecodeError, ValueError) as error:
            raise EvidenceScoringError(f"Invalid response at line {line_number}") from error
        if response.case_id in responses:
            raise EvidenceScoringError(f"Duplicate response for case: {response.case_id}")
        responses[response.case_id] = response.response
    return responses


def _load_expected(path: Path, *, case_id: str) -> Any:
    try:
        payload = yaml.safe_load(path.read_text(encoding="utf-8"))
        checks = payload["checks"]
        if len(checks) != 1:
            raise ValueError("expected one check")
        return checks[0]["expected"]
    except (OSError, KeyError, TypeError, ValueError, yaml.YAMLError) as error:
        raise EvidenceScoringError(f"Invalid answer key for case: {case_id}") from error


def _score_one(response: str, expected: Any) -> Literal["correct", "incorrect", "invalid"]:
    try:
        actual: Any
        if isinstance(expected, bool):
            value = response.strip().casefold()
            if value not in {"true", "false"}:
                return "invalid"
            actual = value == "true"
        elif isinstance(expected, (int, float)):
            actual = type(expected)(response.strip())
        elif isinstance(expected, str):
            actual = response.strip()
        else:
            actual = ast.literal_eval(response.strip())
        return "correct" if _normalise(actual) == _normalise(expected) else "incorrect"
    except (SyntaxError, ValueError, TypeError):
        return "invalid"


def _group_scores(
    scores: list[EvidenceCaseScore],
    *,
    attribute: Literal["target_concept", "task_family"],
) -> tuple[EvidenceGroupScore, ...]:
    groups = sorted({getattr(score, attribute) for score in scores})
    return tuple(
        EvidenceGroupScore(
            group=group,
            case_count=sum(getattr(score, attribute) == group for score in scores),
            correct_count=sum(
                getattr(score, attribute) == group and score.status == "correct" for score in scores
            ),
            accuracy=(
                sum(
                    getattr(score, attribute) == group and score.status == "correct"
                    for score in scores
                )
                / sum(getattr(score, attribute) == group for score in scores)
            ),
        )
        for group in groups
    )


def _normalise(value: Any) -> Any:
    if isinstance(value, list | tuple):
        sequence = cast(list[Any] | tuple[Any, ...], value)
        return tuple(_normalise(item) for item in sequence)
    if isinstance(value, dict):
        mapping = cast(dict[Any, Any], value)
        return tuple(sorted(((key, _normalise(item)) for key, item in mapping.items())))
    return value


def _file_hash(path: Path) -> Sha256:
    from socratic_tutor.benchmark.hashing import file_sha256

    try:
        return file_sha256(path.read_bytes())
    except OSError as error:
        raise EvidenceScoringError(f"Could not hash response file: {path}") from error
